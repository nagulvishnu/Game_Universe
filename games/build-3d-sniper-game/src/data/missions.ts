/**
 * Generates deterministic locally rotating Daily Contracts based on YYYY-MM-DD (works 100% offline).
 */
export function getDailyContracts(dateKey?: string): ContractDefinition[] {
  const today = dateKey ?? new Date().toISOString().slice(0, 10);
  let hash = 0;
  for (let i = 0; i < today.length; i++) {
    hash = (hash * 31 + today.charCodeAt(i)) >>> 0;
  }

  const pickA = hash % CONTRACT_OPERATIONS.length;
  const pickB = (hash + 3) % CONTRACT_OPERATIONS.length;
  const pickC = (hash + 7) % CONTRACT_OPERATIONS.length;

  return [pickA, pickB, pickC].map((idx, slot) => {
    const base = CONTRACT_OPERATIONS[idx];
    return {
      ...base,
      id: `daily_${today}_${slot}`,
      title: `[DAILY] ${base.title}`,
      rewardCredits: Math.round(base.rewardCredits * 1.35),
      rewardXp: Math.round(base.rewardXp * 1.35),
      isDaily: true,
      mission: {
        ...base.mission,
        id: `daily_${today}_${slot}_m`,
        mode: 'daily_contracts',
        codeName: `DAILY OP // ${today}`,
        baseRewardCredits: Math.round(base.rewardCredits * 1.35),
        baseRewardXp: Math.round(base.rewardXp * 1.35),
      },
    };
  });
}

